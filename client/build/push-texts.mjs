// The texts of push notifications, in every language, from push-texts.json (the one source).
// The server sends only their keys and arguments (`%1$s`); Android words them from the
// resources written here, the web's service worker from public/push-texts.js.
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const LANGUAGES = ["en", "ru"];

export function readPushTexts() {
  return JSON.parse(readFileSync(resolve(root, "push-texts.json"), "utf8"));
}

/** Android resource string escaping: apostrophes, quotes, backslashes, XML specials. */
function androidString(text) {
  return text
    .replaceAll("\\", "\\\\")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll("'", "\\'")
    .replaceAll('"', '\\"');
}

const GENERATED = "Generated by build/generate-push-texts.mjs from push-texts.json: edit that file.";

/** The generated files by path (relative to client/), as they should read. */
export function pushTextOutputs(texts = readPushTexts()) {
  const outputs = {};
  for (const language of LANGUAGES) {
    const folder = language === "en" ? "values" : `values-${language}`;
    const lines = Object.entries(texts).map(
      ([key, byLanguage]) => `    <string name="${key}">${androidString(byLanguage[language])}</string>`,
    );
    outputs[`android/app/src/main/res/${folder}/push_strings.xml`] =
      `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${GENERATED} -->\n<resources>\n${lines.join("\n")}\n</resources>\n`;
  }
  const byLanguage = Object.fromEntries(
    LANGUAGES.map((language) => [
      language,
      Object.fromEntries(Object.entries(texts).map(([key, text]) => [key, text[language]])),
    ]),
  );
  outputs["public/push-texts.js"] =
    `// ${GENERATED}\nself.PUSH_TEXTS = ${JSON.stringify(byLanguage, null, 2)};\n`;
  return outputs;
}
